# Rebuilds scripts/apps/panorama-art.js (the size of every panorama sprite) from art/panorama.
# Run from the repo root after adding or changing art: python3 dev/gen-panorama-art.py
import glob, json, os
from PIL import Image
sizes = {os.path.basename(f)[:-4]: list(Image.open(f).size) for f in sorted(glob.glob("art/panorama/*.png"))}
body = ",\n".join(f'  "{k}": [{w}, {h}]' for k, (w, h) in sizes.items())
with open("scripts/apps/panorama-art.js", "w", newline="\n") as out:
    out.write("// Generated by dev/gen-panorama-art.py: the width and height of every panorama sprite in art/panorama.\n")
    out.write("export const ART_SIZES = Object.freeze({\n" + body + "\n});\n")
print(len(sizes), "sprites")
